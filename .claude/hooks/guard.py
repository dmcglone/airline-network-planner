#!/usr/bin/env python3
"""Claude Code PreToolUse guard for this repo. Two jobs, picked by argument.

    guard.py dist    blocks Edit/Write into dist/. It is generated output: a
                     hand-edit there is reverted by the next build, silently.

    guard.py ship    before `git push` or a wrangler deploy, builds and runs
                     verify.py, and blocks the command if either fails. This
                     exists because a commit once shipped on a red test, read
                     as green through `verify.py | tail`.

Exit 0 lets the tool call through. Exit 2 blocks it, and stderr is what Claude
reads as the reason. Exit 1 would be a non-blocking error, so it is never used
for a real failure here.

These hooks only govern Claude. A push from your own terminal is not gated;
CI (.github/workflows/verify.yml) still runs the acceptance test on every push.
"""
import json
import os
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(os.environ.get("CLAUDE_PROJECT_DIR") or
                    pathlib.Path(__file__).resolve().parents[2]).resolve()

SHIP = re.compile(r"(^|[\s;&|(])(git\s+push\b|(npx\s+)?wrangler\s+deploy\b|npm\s+run\s+deploy\b)")

# A hook that crashes exits 1, which Claude Code treats as a NON-blocking error:
# the command goes ahead. The first version of this file did exactly that on
# Windows, where printing verify.py's "FAIL — do not publish" to a cp1252 or
# cp437 stderr raised UnicodeEncodeError, so a failing test let the push
# through. Hence: never crash on output, and in ship mode fail closed.
for _s in (sys.stdout, sys.stderr):
    try:
        _s.reconfigure(errors="replace")
    except (AttributeError, ValueError):
        pass

CHILD_ENV = {**os.environ, "PYTHONIOENCODING": "utf-8", "PYTHONUTF8": "1"}


def block(reason):
    try:
        print(reason, file=sys.stderr)
    except Exception:
        pass                      # the block matters more than the message
    sys.exit(2)


def read_input():
    try:
        return json.load(sys.stdin)
    except ValueError:
        return {}


def guard_dist(data):
    path = (data.get("tool_input") or {}).get("file_path") or ""
    if not path:
        return
    p = pathlib.Path(path)
    if not p.is_absolute():
        p = pathlib.Path(data.get("cwd") or ROOT) / p
    try:
        rel = p.resolve().relative_to(ROOT)
    except ValueError:
        return                                  # outside the repo: not our business
    if rel.parts and rel.parts[0] == "dist":
        block(f"Blocked: {rel.as_posix()} is generated by build.py. Edit the part "
              "in src/ (or src/data/, or network.json) and rebuild. A hand-edit "
              "in dist/ is reverted by the next build without warning.")


def run(script, *args):
    """Run a repo script and return (exit code, last lines of output).
    Never piped: the exit code is the script's own."""
    r = subprocess.run([sys.executable, str(ROOT / script), *args], cwd=ROOT, env=CHILD_ENV,
                       capture_output=True, text=True, encoding="utf-8", errors="replace")
    tail = "\n".join((r.stdout + r.stderr).strip().splitlines()[-30:])
    return r.returncode, tail


def guard_ship(data):
    cmd = (data.get("tool_input") or {}).get("command") or ""
    if not SHIP.search(cmd):
        return                                  # the `if` filter is best-effort; re-check

    # The gate tests the working tree. If src/ has uncommitted changes, a pass
    # here says nothing about what a push would actually send.
    if re.search(r"\bgit\s+push\b", cmd):
        st = subprocess.run(["git", "status", "--porcelain", "--", "src", "network.json",
                             "build.py", "engine.py", "validate.py", "verify.py"],
                            cwd=ROOT, capture_output=True, text=True)
        if st.stdout.strip():
            block("Blocked: uncommitted changes to the model would not be in this push, "
                  "so verifying the working tree would test the wrong thing:\n"
                  + st.stdout.rstrip() + "\nCommit or stash them, then push again.")

    try:
        import playwright  # noqa: F401
    except ImportError:
        block("Blocked: verify.py needs Playwright and it is not installed for "
              f"{sys.executable}. Run:\n"
              "    python -m pip install playwright\n"
              "    python -m playwright install chromium\n"
              "then try again. Do not skip the acceptance test.")

    code, out = run("build.py")
    if code != 0:
        block(f"Blocked: build.py failed (exit {code}).\n{out}")
    code, out = run("verify.py")
    if code != 0:
        block(f"Blocked: verify.py failed (exit {code}). Find the cause. Never edit "
              f"an expected value in verify.py to make it pass.\n{out}")
    # Passed: say nothing and let the command run.


def main():
    mode = sys.argv[1] if len(sys.argv) > 1 else ""
    data = read_input()
    if mode == "dist":
        guard_dist(data)
    elif mode == "ship":
        try:
            guard_ship(data)
        except SystemExit:
            raise
        except Exception as e:            # fail closed: an unverified push is the worst case
            block(f"Blocked: the push gate itself crashed ({type(e).__name__}: {e}), "
                  "so nothing was verified. Fix .claude/hooks/guard.py rather than "
                  "pushing around it.")
    sys.exit(0)


if __name__ == "__main__":
    main()
